export function buildOrderbookFromMarket(market: KalshiMarket, seedOffset = 0): OrderBook {
  const yb = market.yesBid;
  const nb = market.noBid;
  const waveA = Math.round(Math.sin(seedOffset * 0.7 + yb * 0.3) * 120);
  const waveB = Math.round(Math.cos(seedOffset * 0.5 + nb * 0.3) * 95);
  return {
    ticker: market.ticker,
    yesBids: [
      { price: yb, quantity: Math.max(80, 420 + waveA) },
      { price: Math.max(1, yb - 1), quantity: Math.max(150, 680 + Math.round(waveA * 0.8)) },
      { price: Math.max(1, yb - 2), quantity: Math.max(250, 1150 - Math.round(waveB * 0.6)) },
      { price: Math.max(1, yb - 4), quantity: Math.max(400, 1900 + waveB) },
      { price: Math.max(1, yb - 7), quantity: Math.max(600, 2600 - waveA) },
    ],
    noBids: [
      { price: nb, quantity: Math.max(80, 310 + waveB) },
      { price: Math.max(1, nb - 1), quantity: Math.max(150, 540 + Math.round(waveB * 0.7)) },
      { price: Math.max(1, nb - 2), quantity: Math.max(250, 890 - Math.round(waveA * 0.5)) },
      { price: Math.max(1, nb - 4), quantity: Math.max(400, 1450 + waveA) },
      { price: Math.max(1, nb - 7), quantity: Math.max(600, 2100 - waveB) },
    ],
    updatedAt: new Date().toISOString(),
  };
}

